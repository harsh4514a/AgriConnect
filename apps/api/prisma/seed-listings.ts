async function main() {
  console.log('Seeding marketplace listings...');

  let created = 0;
  let skipped = 0;

  for (const listing of SAMPLE_LISTINGS) {
    const existing = await prisma.listing.findUnique({ where: { id: listing.id } });
    if (existing) {
      skipped += 1;
      continue;
    }

    await prisma.listing.create({ data: listing });
    created += 1;
    console.log(`  Created listing: ${listing.cropKey} — ${listing.farmerName} (${listing.district})`);
  }

  console.log(`\nDone. Created: ${created}, Skipped (already exist): ${skipped}`);
}

main()
  .catch(() => {
    console.error('Seed listings failed. This development sample seed is not for production.');
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
